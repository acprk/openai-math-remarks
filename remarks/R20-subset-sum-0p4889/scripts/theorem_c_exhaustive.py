# Exhaustive check of Proposition C (note, Section 5):
#   G = (Z/p^e)^k, K <= G a subgroup of index M  ==>  |K cap G[p]| >= p^k M^{-1/e},
#   with equality iff G/K is free over Z/p^e (i.e. G/K = (Z/p^e)^s); freeness is tested independently via
#   |G/K| = |(G/K)[p]|^e.
# Also checks the averaged corollary: for the uniform distribution on subgroups of index M,
#   max_{0 != g in G[p]} Pr[g in K] >= (p^k M^{-1/e} - 1)/(p^k - 1)
# (in fact the uniform distribution is only one example; the corollary holds for every distribution).
# Enumeration: all subgroups by closure under adding one generator at a time (BFS from {0}).
# Usage: python3 -u theorem_c_exhaustive.py     Environment: CPython 3.10; single thread; ~1-2 min.
from itertools import product
from fractions import Fraction
from collections import defaultdict


def subgroups(q, k):
    els = list(product(range(q), repeat=k))
    idx = {g: i for i, g in enumerate(els)}
    add = lambda x, y: tuple((a + b) % q for a, b in zip(x, y))
    zero = tuple([0] * k)

    def join(H, g):          # subgroup generated by H and g
        S = set(H); frontier = [g] if g not in S else []
        # multiples of g added to every element of H
        mult = []; x = zero
        while True:
            x = add(x, g)
            if x == zero:
                break
            mult.append(x)
        new = set(S)
        for hh in S:
            for m in mult:
                new.add(add(hh, m))
        return frozenset(new)

    start = frozenset([zero]); seen = {start}; stack = [start]
    while stack:
        H = stack.pop()
        for g in els:
            if g in H:
                continue
            J = join(H, g)
            if J not in seen:
                seen.add(J); stack.append(J)
    return seen


ALL = {}


def check(p, e, k):
    q = p ** e
    ALL[q, k] = list(product(range(q), repeat=k))
    subs = subgroups(q, k)
    Gp = [g for g in product(range(q), repeat=k) if all((p * a) % q == 0 for a in g)]
    nG = q ** k
    worst = None; n_eq = 0; n_free = 0; bad = 0
    byM = defaultdict(list)
    for K in subs:
        M = nG // len(K)
        c = sum(1 for g in Gp if g in K)
        # compare c^e >= p^{k e} / M   (exact integer form of c >= p^k M^{-1/e})
        lhs, rhs = c ** e * M, p ** (k * e)
        if lhs < rhs:
            bad += 1
        ratio = Fraction(lhs, rhs)
        if worst is None or ratio < worst:
            worst = ratio
        # G/K free over Z/p^e  <=>  |G/K| = |(G/K)[p]|^e, where |(G/K)[p]| = #{g in G : p g in K} / |K|
        # (computed directly from K, independently of c = |K cap G[p]|)
        Kset = K
        quotp = sum(1 for g in ALL[q, k] if tuple((p * a) % q for a in g) in Kset) // len(K)
        free = (M == quotp ** e)
        n_free += free
        if lhs == rhs:
            n_eq += 1
            if not free:
                bad += 1
        elif free:
            bad += 1
        byM[M].append(K)
    # averaged corollary for the uniform distribution on the subgroups of each index
    avg_ok = True
    Gp_nz = [g for g in Gp if any(g)]
    for M, Ks in byM.items():
        best = max(sum(1 for K in Ks if g in K) for g in Gp_nz) if Gp_nz else 0
        lower = Fraction(1, 1)  # compare best/len(Ks) >= (p^k M^{-1/e} - 1)/(p^k - 1) via e-th powers
        # (p^k M^{-1/e} - 1) <= (p^k - 1) * best/len(Ks)  <=>  p^k M^{-1/e} <= 1 + (p^k-1) best/len(Ks)
        t = 1 + Fraction((p ** k - 1) * best, len(Ks))
        if not (Fraction(p ** (k * e), M) <= t ** e):
            avg_ok = False
    print('G = (Z/%d)^%d : %4d subgroups ; violations %d ; min (|K cap G[p]|^e M / p^{ke}) = %s ; '
          'equality cases %d ; free quotients (G/K = (Z/p^e)^s) %d, equality <=> free: %s ; averaged corollary %s'
          % (q, k, len(subs), bad, worst, n_eq, n_free, 'ok' if bad == 0 else 'FAIL', 'ok' if avg_ok else 'FAIL'))
    return bad == 0 and avg_ok


ok = True
for (p, e, k) in [(2, 2, 2), (2, 2, 3), (2, 3, 2), (2, 4, 2), (3, 2, 2), (3, 3, 2), (5, 2, 2)]:
    ok &= check(p, e, k)
print('ALL PROPOSITION C CHECKS PASS:', ok)
